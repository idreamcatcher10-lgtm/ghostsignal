import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { createPacket, encodePacket } from '../dist/assets/codec.js';

function loadBrowserCode(path, context) {
  vm.runInContext(readFileSync(new URL(path, import.meta.url), 'utf8'), context, { timeout: 15000 });
}

function createPixelQr(encoder, payload) {
  const qr = new encoder.QRCode(-1, encoder.correction.M);
  qr.addData(payload);
  qr.make();
  const quiet = 4;
  const modulePixels = 6;
  const count = qr.getModuleCount();
  const side = (count + quiet * 2) * modulePixels;
  const data = new Uint8ClampedArray(side * side * 4);
  data.fill(255);
  for (let row = 0; row < count; row++) {
    for (let col = 0; col < count; col++) {
      if (!qr.isDark(row, col)) continue;
      for (let y = (row + quiet) * modulePixels; y < (row + quiet + 1) * modulePixels; y++) {
        for (let x = (col + quiet) * modulePixels; x < (col + quiet + 1) * modulePixels; x++) {
          const offset = (y * side + x) * 4;
          data[offset] = 16; data[offset + 1] = 27; data[offset + 2] = 23;
        }
      }
    }
  }
  return { data, side };
}

test('bundled offline decoder reads a QR generated by the bundled QR encoder', () => {
  const context = vm.createContext({
    console, Uint8ClampedArray, Uint8Array, ArrayBuffer, DataView, TextEncoder, TextDecoder,
  });
  loadBrowserCode('../dist/assets/qr-vendor.js', context);
  loadBrowserCode('../dist/assets/jsqr.js', context);
  assert.equal(typeof context.jsQR, 'function');
  const packet = createPacket('Station A', 'Water needed at shelter B', 'sos', 24);
  const value = encodePacket(packet);
  const pixels = createPixelQr(context.GhostQR, value);
  const result = context.jsQR(pixels.data, pixels.side, pixels.side, { inversionAttempts: 'attemptBoth' });
  assert.equal(result?.data, value);
});
